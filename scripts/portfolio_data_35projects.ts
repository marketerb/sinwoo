/**
 * TypeScript 타입 정의
 */
export interface Portfolio {
  title: string;
  location: string;
  description: string;
  status: string;
  image_url: null | string;
  gradient: string;
}

/**
 * Supabase INSERT SQL 쿼리 생성 함수
 */
export function generateSqlInserts(): string {
  const sqlLines = portfolioProjects.map((project: Portfolio) => {
    const title = project.title.replace(/'/g, "''");
    const location = project.location.replace(/'/g, "''");
    const description = project.description.replace(/'/g, "''");
    const image_url = (project.image_url as string | null)
      ? `'${(project.image_url as string).replace(/'/g, "''")}'`
      : "NULL";

    return `('${title}', '${description}', '${location}', '${project.status}', ${image_url})`;
  });

  return `INSERT INTO portfolios (title, description, location, status, image_url) VALUES\n${sqlLines.join(",\n")};`;
}

/**
 * 그래디언트 색상 할당 (Tailwind CSS)
 */
export function getGradientByIndex(index: number): string {
  const gradients = [
    "from-yellow-700 to-yellow-900",
    "from-amber-700 to-amber-900",
    "from-orange-700 to-orange-900",
    "from-yellow-600 to-yellow-800",
    "from-amber-600 to-amber-800",
    "from-orange-600 to-orange-800",
  ];
  return gradients[index % gradients.length];
}

